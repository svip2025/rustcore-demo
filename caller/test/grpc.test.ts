import assert from "node:assert/strict";
import test, { type TestContext } from "node:test";
import { setTimeout as delay } from "node:timers/promises";
import { fileURLToPath } from "node:url";
import { join } from "node:path";
import * as grpc from "@grpc/grpc-js";
import * as protoLoader from "@grpc/proto-loader";
import { CoreRpc } from "../src/grpc.js";

type Message = Record<string, unknown>;
const protoDir = fileURLToPath(new URL("../../rustcore/proto/", import.meta.url));
const definitions = grpc.loadPackageDefinition(protoLoader.loadSync([
  join(protoDir, "execution_engine_v2.proto"), join(protoDir, "execution_engine_vnext.proto"),
], { keepCase: true, longs: String, enums: String, defaults: true, arrays: true, oneofs: true }));
// The cast is limited to the three constructors generated by these exact protos.
const packages = definitions as unknown as { execution_engine: {
  v2: { EngineExecution: grpc.ServiceClientConstructor };
  vnext: { EngineExecution: grpc.ServiceClientConstructor; EngineEvents: grpc.ServiceClientConstructor };
} };

async function serve(t: TestContext, handlers: {
  v2?: grpc.UntypedServiceImplementation;
  next?: grpc.UntypedServiceImplementation;
  events?: grpc.UntypedServiceImplementation;
}): Promise<string> {
  const server = new grpc.Server();
  if (handlers.v2) server.addService(packages.execution_engine.v2.EngineExecution.service, handlers.v2);
  if (handlers.next) server.addService(packages.execution_engine.vnext.EngineExecution.service, handlers.next);
  if (handlers.events) server.addService(packages.execution_engine.vnext.EngineEvents.service, handlers.events);
  const port = await new Promise<number>((resolve, reject) => {
    server.bindAsync("127.0.0.1:0", grpc.ServerCredentials.createInsecure(), (error, port) => error ? reject(error) : resolve(port));
  });
  t.after(() => server.forceShutdown());
  return `127.0.0.1:${port}`;
}

function client(t: TestContext, address: string, options: { token?: string; deadlineMs?: number } = {}): CoreRpc {
  const rpc = new CoreRpc({ address, protoDir, ...options });
  t.after(() => rpc.close());
  return rpc;
}

function record(value: unknown): Message {
  assert.ok(value !== null && typeof value === "object" && !Array.isArray(value));
  return value as Message;
}

test("protobuf empty buffers restore ordinary scalar defaults but never optional money/quantity", async (t) => {
  const accountMethod = packages.execution_engine.v2.EngineExecution.service.GetAccountState!;
  assert.deepEqual(accountMethod.responseSerialize({}), Buffer.alloc(0), "same omitted false/0 encoding as Prost");
  let authorization: grpc.MetadataValue[] = [];
  const address = await serve(t, { v2: {
    GetAccountState: (call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => {
      authorization = call.metadata.get("authorization");
      assert.equal(call.request.credential_id, "demo-a");
      assert.equal(Object.hasOwn(call.request, "credentialId"), false);
      reply(null, {});
    },
    GetPositionStates: (_call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => reply(null, {}),
    GetAccountOrderState: (_call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => reply(null, {
      local: { protection_orders: { meta: { coverage: "AOC_COMPLETE_LOCAL" }, rows: [] } },
      venue: { availability: "AOA_AVAILABLE", algo: { meta: { coverage: "AOC_COMPLETE_VENUE" }, rows: [{ identity_valid: true, algo_id: "9007199254740997" }] } },
    }),
  } });
  const rpc = client(t, address, { token: "synthetic-local-token" });
  const account = await rpc.unary("v2", "GetAccountState", { credential_id: "demo-a", schema_version: 1 });
  assert.deepEqual(authorization, ["Bearer synthetic-local-token"]);
  assert.equal(account.available, false);
  assert.equal(account.as_of_ms, "0");
  assert.deepEqual(account.positions, []);
  for (const optional of ["equity_usdt", "available_usdt", "used_margin_usdt", "today_realized_pnl_usdt", "open_positions_count", "observed_at_ms"])
    assert.equal(Object.hasOwn(account, optional), false, optional);
  const positions = await rpc.unary("v2", "GetPositionStates", { credential_id: "demo-a" });
  assert.deepEqual(positions.positions, []);
  assert.deepEqual(positions.orphan_positions, []);
  const state = await rpc.unary("v2", "GetAccountOrderState", { credential_id: "demo-a" });
  const venue = record(state.venue), algo = record(venue.algo), meta = record(algo.meta);
  assert.equal(venue.availability, "AOA_AVAILABLE");
  assert.equal(meta.coverage, "AOC_COMPLETE_VENUE");
  assert.equal(meta.overflow, false);
  assert.equal(meta.returned_count, 0);
  assert.equal(Object.hasOwn(meta, "total_count"), false, "optional count is not invented");
  assert.ok(Array.isArray(algo.rows));
  const order = record(algo.rows[0]);
  assert.equal(order.algo_id, "9007199254740997");
  for (const optional of ["quantity", "reduce_only", "close_position", "actual_order_id", "trigger_price"])
    assert.equal(Object.hasOwn(order, optional), false, optional);
});

test("large 64-bit request/response values stay strings and exact versioned services are used", async (t) => {
  let seenRevision: unknown;
  const address = await serve(t, {
    v2: {
      ClosePosition: (call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => {
        seenRevision = call.request.expected_revision;
        reply(null, { target_revision: call.request.expected_revision, request_status: "working", schema_version: 1 });
      },
      ReconcileNow: (_call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => reply(null, { accepted: true, completed: true, message: "v2" }),
    },
    next: { ReconcileNow: (_call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => reply(null, { accepted: true, message: "next" }) },
  });
  const rpc = client(t, address);
  const response = await rpc.unary("v2", "ClosePosition", { expected_revision: "9007199254740993" });
  assert.equal(seenRevision, "9007199254740993");
  assert.equal(response.target_revision, "9007199254740993");
  assert.equal(Object.hasOwn(response, "engine_order_id"), false);
  assert.equal((await rpc.unary("v2", "ReconcileNow", {})).message, "v2");
  assert.equal((await rpc.unary("next", "ReconcileNow", {})).message, "next");
  await assert.rejects(rpc.unary("v2", "NotAnRpc", {}), /Unknown or incompatible/);
});

test("a write timeout has a deadline and is never automatically resubmitted", async (t) => {
  let attempts = 0;
  const address = await serve(t, { v2: {
    GetAccountState: (_call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => reply(null, {}),
    ClosePosition: (_call: grpc.ServerUnaryCall<Message, Message>, _reply: grpc.sendUnaryData<Message>) => { attempts++; },
  } });
  const rpc = client(t, address, { deadlineMs: 200 });
  await rpc.unary("v2", "GetAccountState", {}); // Establish the channel before measuring the server timeout.
  await assert.rejects(rpc.unary("v2", "ClosePosition", {}), (error: unknown) => {
    assert.equal(record(error).code, grpc.status.DEADLINE_EXCEEDED);
    return true;
  });
  await delay(20);
  assert.equal(attempts, 1);
});

test("an unavailable write result is returned to the caller once without a retry", async (t) => {
  let attempts = 0;
  const address = await serve(t, { v2: {
    ClosePosition: (_call: grpc.ServerUnaryCall<Message, Message>, reply: grpc.sendUnaryData<Message>) => {
      attempts++;
      reply({ code: grpc.status.UNAVAILABLE, message: "synthetic unknown write outcome" });
    },
  } });
  const rpc = client(t, address);
  await assert.rejects(rpc.unary("v2", "ClosePosition", {}), (error: unknown) => {
    assert.equal(record(error).code, grpc.status.UNAVAILABLE);
    return true;
  });
  await delay(20);
  assert.equal(attempts, 1);
});

test("vNext StreamEvents preserves cursor/token/payload; intentional cancel is not an error", async (t) => {
  let serverCancelled!: () => void;
  const cancelled = new Promise<void>((resolve) => { serverCancelled = resolve; });
  let request: Message | undefined, authorization: grpc.MetadataValue[] = [];
  const address = await serve(t, { events: {
    StreamEvents: (call: grpc.ServerWritableStream<Message, Message>) => {
      request = call.request;
      authorization = call.metadata.get("authorization");
      call.on("cancelled", serverCancelled);
      call.write({ seq: "9007199254740999", event_id: "event-one", payload_json: Buffer.from('{"kind":"fixture"}') });
    },
  } });
  const rpc = client(t, address, { token: "synthetic-stream-token" });
  const errors: Error[] = [];
  let resolveData!: (value: Message) => void;
  const data = new Promise<Message>((resolve) => { resolveData = resolve; });
  const subscription = rpc.streamEvents({ credential_id: "demo-a", since_seq: "9007199254740998" }, resolveData, (error) => errors.push(error));
  const event = await data;
  assert.equal(request?.since_seq, "9007199254740998");
  assert.deepEqual(authorization, ["Bearer synthetic-stream-token"]);
  assert.equal(event.seq, "9007199254740999");
  assert.deepEqual(event.payload_json, Buffer.from('{"kind":"fixture"}'));
  subscription.cancel(); subscription.cancel();
  await cancelled;
  await delay(20);
  assert.equal(errors.length, 0);
  rpc.close(); rpc.close();
  await assert.rejects(rpc.unary("v2", "GetAccountState", {}), /closed/);
});

test("remote stream completion is surfaced once and never reconnects itself", async (t) => {
  let attempts = 0;
  const address = await serve(t, { events: {
    StreamEvents: (call: grpc.ServerWritableStream<Message, Message>) => { attempts++; call.end(); },
  } });
  const rpc = client(t, address);
  let resolveError!: (error: Error) => void;
  const error = new Promise<Error>((resolve) => { resolveError = resolve; });
  let errors = 0;
  rpc.streamEvents({}, () => assert.fail("empty stream"), (failure) => { errors++; resolveError(failure); });
  assert.match((await error).message, /ended by the server/);
  await delay(20);
  assert.equal(errors, 1);
  assert.equal(attempts, 1);
});
